"""
player_analytics.py  -  Step 3 of the analytics engine
======================================================

Player-level analytics built on top of ``MetricsEngine`` (metrics_engine.py):

 1. Decision Efficiency (counterfactual): for every pass, compare the EXPECTED change in EPV of the
    pass the player chose with every other option he had among the teammates on the pitch.
        decision score = rank of the chosen option among all options (1 = best, 0 = worst)
        regret         = best option's dEPV - chosen option's dEPV  (EPV units)
    The min-max score and the old ratio dEPV_chosen / dEPV_max are kept as secondary columns.
 2. Tactical & physical fatigue decay: 15-minute blocks (see BIN_LABELS). Tracks the player's own
    pitch-control area A_i (and radius sqrt(A/pi)), VAEP per action, decision score and distance.
 3. Pairwise chemistry: passer->receiver EPV uplift = dEPV_actual - E[dEPV] where E[dEPV] is the
    average completed pass from the same pitch zone. Pairs need >= 3 completed passes.
 4. Decoy Run Index: space (change in DAS for TEAMMATES) created by off-ball runs that did not
    end up receiving the ball.
 5. Press Resistance Rating: value generated by successful actions when the opponent's pitch
    control on the ball handler is above 0.65.

Heavy parts are computed once (a minute or two for a full match), then cached on disk in
``data/interim/analytics_<match>_<version>.pkl``.

Self-test:   python player_analytics.py --match 3816
"""
