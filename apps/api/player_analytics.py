PRESS_LEVELS = ((0.0, 0.25, "low"), (0.25, 0.6, "medium"), (0.6, 1.01, "high"))
PRESS_SENSITIVITY_M = (2.0, 3.0, 4.0)  # how much the "pressured" count depends on the chosen radius
FATIGUE_SAMPLE_S = 15.0  # one pitch-control snapshot every 15 s of the match
MIN_MINUTES_FOR_TREND = 3.0  # a block needs at least this much playing time to be compared


def _wilson(k: int, n: int, z: float = 1.96) -> tuple[Optional[float], Optional[float]]:
    """95 % Wilson interval for a share k/n (honest about small samples)."""
    if n <= 0:
        return None, None
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return float(max(0.0, centre - half)), float(min(1.0, centre + half))


def _native(x):
    """Make nested results JSON friendly (numpy -> python, NaN -> None)."""
    if isinstance(x, dict):
        return {str(k): _native(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_native(v) for v in x]
    if isinstance(x, np.ndarray):
        return _native(x.tolist())
    if isinstance(x, (np.integer,)):
        return int(x)
    if isinstance(x, (np.floating, float)):
        return None if not np.isfinite(x) else float(x)
    if isinstance(x, (np.bool_,)):
        return bool(x)
    if isinstance(x, pd.DataFrame):
        return _native(x.to_dict("records"))
    if x is pd.NA or x is pd.NaT:
        return None
    return x


class PlayerAnalytics:
    def __init__(self, engine: MetricsEngine, data_dir: Optional[Path] = None):
        self.e = engine
        self.m = engine.m
        self.data_dir = Path(data_dir) if data_dir else default_data_dir()
        self._lock = threading.RLock()
        self._res: dict = {}
        self.ready = {"decisions": False, "press": False, "fatigue": False, "decoys": False}
        self._players = self.m.players
        self._side_arr = self._players["side"].to_numpy()

    # =====================================================================
    # helpers
    # =====================================================================
    def _model_stamp(self) -> str:
        """Changes whenever the fitted pass model / calibration files change, so stale results are never reused."""
        from metrics_engine import ASSETS_DIR
        parts = []
        for name in ("pass_model_fitted.json", "pass_calibration_lane.json"):
            f = ASSETS_DIR / name
            parts.append(str(int(f.stat().st_mtime)) if f.exists() else "0")
        try:  # also depends on the exact data files, so replacing a match's events file never reuses old results
            import hashlib
            from data_loader import find_match_files
            ff = find_match_files(self.m.match_id, self.data_dir)
            sig = "|".join(f"{k}:{ff[k].name}:{ff[k].stat().st_size}:{int(ff[k].stat().st_mtime)}" for k in ("tracking", "events", "metadata", "roster") if ff.get(k))
            parts.append(hashlib.md5(sig.encode()).hexdigest()[:8])
        except Exception:
            parts.append("x")
        return "_" + "-".join(parts)

    def _cache_file(self) -> Path:
        return self.data_dir / "interim" / f"analytics_{self.m.match_id}_{ANALYTICS_VERSION}_L{LOADER_VERSION}_{self.m.n_frames}_{int(self.e.pc_params.use_acceleration)}_{self.e.pass_model}{self._model_stamp()}.pkl"

    def player_row(self, player_id) -> pd.Series:
        p = self._players[self._players["player_id"] == str(player_id)]
        if not len(p):
            raise KeyError(f"player {player_id} not found")
        return p.iloc[0]

    def _name(self, slot: int) -> str:
        return str(self._players.iloc[int(slot)]["name"]) if slot is not None and int(slot) >= 0 else "?"

    def players_list(self) -> list[dict]:
        m = self.m
        out = []
        for _, r in self._players.iterrows():
            out.append({
                "slot": int(r["slot"]), "player_id": r["player_id"], "name": r["name"], "jersey": r["jersey"],
                "side": r["side"], "team": r["team_name"], "position": r["position"],
                "minutes_tracked": round(float(r["frames_present"]) / m.fps / 60.0, 1),
            })
        return out

    # =====================================================================
    # warm-up (everything heavy, cached on disk)
    # =====================================================================
    def warm(self, progress: Optional[Callable[[str], None]] = None, force: bool = False) -> None:
        log = progress or (lambda s: None)
        with self._lock:
            cf = self._cache_file()
            if not force and cf.exists() and not self.ready["fatigue"]:
                try:
                    with open(cf, "rb") as f:
                        self._res = pickle.load(f)
                    for k in self.ready:
                        self.ready[k] = k in self._res
                    log("analytics loaded from cache")
                    if all(self.ready.values()):
                        return
                except Exception:
                    self._res = {}
            for name, fn in (("decisions", self._compute_decisions), ("press", self._compute_press),
                             ("fatigue", self._compute_fatigue), ("decoys", self._compute_decoys)):
                if self.ready[name]:
                    continue
                t = time.time()
                log(f"computing {name} ...")
                self._res[name] = fn()
                self.ready[name] = True
                log(f"  {name} done in {time.time() - t:.1f}s")
            cf.parent.mkdir(parents=True, exist_ok=True)
            with open(cf, "wb") as f:
                pickle.dump(self._res, f, protocol=pickle.HIGHEST_PROTOCOL)

    def _get(self, name: str) -> pd.DataFrame:
        with self._lock:
            if not self.ready[name]:
                self.warm()
            return self._res[name]

    # =====================================================================
    # 1. Decision efficiency (counterfactual)
    # =====================================================================
    def _compute_decisions(self) -> pd.DataFrame:
        """Counterfactual pass decisions.

        For every pass we list ALL teammates on the pitch as options and give each one an expected EPV gain:
            E[dEPV_j] = p_j * EPV(j) + (1 - p_j) * (-EPV_opponent(j)) - EPV(ball)
        where p_j is the completion probability from the engine (distance, control at the target, open lane).
        The player's intended target (known even if the pass failed) is then compared with the other options:

            regret          = max_j E[dEPV_j] - E[dEPV_chosen]            (EPV units, always >= 0)
            decision_score  = rank of the chosen option among all options, 1 = best option, 0 = worst
            score_minmax    = (chosen - worst) / (best - worst)           (the min-max version)
            ratio_score     = chosen / best  (clipped 0..1; 1/0 rule when best <= 0)   [legacy]

        Passes with fewer than 3 options get no score (a rank among 1-2 options means nothing)."""
        m, e = self.m, self.e
        av = e.action_values()
        ev = m.events
        rows = []
        if not len(av):
            return pd.DataFrame()
        for r in av[av["action"] == "pass"].itertuples():
            if r.slot < 0:
                continue
            fi, side = int(r.frame_idx), r.side
            opp = "away" if side == "home" else "home"
            adir, odir = m.attack_direction(side, fi), m.attack_direction(opp, fi)
            slots = m.present_slots(fi)
            cand = slots[(self._side_arr[slots] == side) & (slots != r.slot)]
            if cand.size == 0:
                continue
            pts = np.column_stack([m.X[fi, cand], m.Y[fi, cand]]).astype(float)
            origin = np.array([r.x, r.y])
            p = e.pass_probabilities(fi, side, origin, pts)
            v_succ = np.asarray(e.epv.value(pts[:, 0], pts[:, 1], adir))
            v_fail = -np.asarray(e.epv.value(pts[:, 0], pts[:, 1], odir))
            exp_delta = p * v_succ + (1 - p) * v_fail - r.epv_before

            e_row = ev.loc[r.event_idx]
            chosen = int(e_row["target_slot"]) if e_row["target_slot"] >= 0 else int(e_row["receiver_slot"])
            if chosen not in cand and np.isfinite(r.end_x):  # fall back: teammate nearest to where the ball went
                chosen = int(cand[np.argmin(np.hypot(pts[:, 0] - r.end_x, pts[:, 1] - r.end_y))])
            if chosen not in cand:
                continue
            k = int(np.flatnonzero(cand == chosen)[0])
            n = int(cand.size)
            ch, mx, mn = float(exp_delta[k]), float(exp_delta.max()), float(exp_delta.min())
            best = int(cand[int(exp_delta.argmax())])
            worse = float((exp_delta < ch - 1e-12).sum())
            ties = float((np.abs(exp_delta - ch) <= 1e-12).sum()) - 1.0
            rank_score = (worse + 0.5 * ties) / (n - 1) if n >= 3 else np.nan
            minmax = ((ch - mn) / (mx - mn) if (mx - mn) > 1e-9 else 1.0) if n >= 3 else np.nan
            if mx <= 0:
                raw, ratio_score = np.nan, (1.0 if ch >= mx - 1e-12 else 0.0)
            else:
                raw = ch / mx
                ratio_score = float(np.clip(raw, 0.0, 1.0))
            rows.append({
                "event_idx": r.event_idx, "frame_num": r.frame_num, "period": r.period, "match_minute": r.match_minute,
                "bin_id": r.bin_id, "side": side, "slot": int(r.slot), "chosen_slot": chosen, "best_slot": best,
                "n_options": n, "chosen_exp_depv": ch, "max_exp_depv": mx, "min_exp_depv": mn, "regret": mx - ch,
                "chosen_p": float(p[k]), "ratio_raw": raw, "ratio_score": ratio_score,
                "decision_score": rank_score, "score_minmax": minmax,
                "success": bool(r.success), "realised_depv": float(r.delta_epv),
            })
        return pd.DataFrame(rows)

    def decision_report(self, slot: int, max_rows: int = 400) -> dict:
        d = self._get("decisions")
        if not len(d):
            return {"summary": {"n_passes": 0}, "passes": []}
        mine = d[d["slot"] == slot].sort_values("match_minute")
        scored = mine.dropna(subset=["decision_score"])

        def mean(col, df=scored):
            return float(df[col].mean()) if len(df) else None

        summ = {
            "n_passes": int(len(mine)),
            "n_scored": int(len(scored)),
            "mean_decision_score": mean("decision_score"),
            "mean_score_minmax": mean("score_minmax"),
            "mean_ratio_score": mean("ratio_score", mine),
            "mean_regret": mean("regret", mine),
            "optimal_choice_rate": float((mine["chosen_slot"] == mine["best_slot"]).mean()) if len(mine) else None,
            "mean_chosen_depv": mean("chosen_exp_depv", mine),
            "mean_max_depv": mean("max_exp_depv", mine),
            "mean_realised_depv": mean("realised_depv", mine),
            "pass_success_rate": float(mine["success"].mean()) if len(mine) else None,
        }
        rows = mine.head(max_rows).copy()
        rows["chosen_name"] = rows["chosen_slot"].map(self._name)
        rows["best_name"] = rows["best_slot"].map(self._name)
        keep = ["frame_num", "period", "match_minute", "chosen_name", "best_name", "n_options", "chosen_exp_depv",
                "max_exp_depv", "regret", "decision_score", "score_minmax", "ratio_score", "success", "realised_depv"]
        return {"summary": summ, "passes": rows[keep]}

    # =====================================================================
    # 5. Press resistance
    # =====================================================================
    def _compute_press(self) -> pd.DataFrame:
        """Was the player closed down when he acted?  Distance from him to the nearest opponent at the moment of the action.
        (The earlier version used the opponent's pitch control on his square; it called only ~2 % of the actions that the
        provider labels as pressured, a nearest-opponent distance of 3 m reproduces that label far better.)"""
        m, e = self.m, self.e
        av = e.action_values()
        side_arr = m.players["side"].to_numpy()
        rows = []
        for r in av.itertuples() if len(av) else []:
            if r.slot < 0:
                continue
            fi = int(r.frame_idx)
            opp_slots = np.flatnonzero((side_arr != r.side) & np.isfinite(m.X[fi]))
            x, y = m.X[fi, r.slot], m.Y[fi, r.slot]
            if not np.isfinite(x):
                x, y = r.x, r.y
            if not len(opp_slots) or not np.isfinite(x):
                continue
            dists = np.hypot(m.X[fi, opp_slots] - x, m.Y[fi, opp_slots] - y)
            d = float(np.min(dists))
            # continuous pressure 0..1: every opponent within PRESS_FADE_M adds weight (1 - d/fade); several close defenders
            # add up but the total never exceeds 1 ("noisy-OR").  0 = nobody near, 1 = an opponent is on top of him.
            w = np.clip(1.0 - dists / PRESS_FADE_M, 0.0, 1.0)
            pressure = float(1.0 - np.prod(1.0 - w))
            rows.append({"event_idx": r.event_idx, "slot": int(r.slot), "side": r.side, "action": r.action,
                         "match_minute": r.match_minute, "bin_id": r.bin_id, "success": bool(r.success),
                         "vaep": r.vaep_oa, "nearest_opp_m": d, "pressured": d < PRESS_RADIUS_M,
                         "pressure": pressure, "n_opp_within_5m": int((dists < PRESS_FADE_M).sum())})
        return pd.DataFrame(rows)

    def press_report(self, slot: int) -> dict:
        d = self._get("press")
        if not len(d):
            return {"n_actions": 0}
        mine = d[d["slot"] == slot]
        pr = mine[mine["pressured"]]
        ok = pr[pr["success"]]
        n_pr = len(pr)
        value = float(ok["vaep"].sum()) if n_pr else 0.0
        levels = []
        for lo, hi, name in PRESS_LEVELS:
            g = mine[(mine["pressure"] >= lo) & (mine["pressure"] < hi)]
            levels.append({"level": name, "n": int(len(g)), "success_rate": float(g["success"].mean()) if len(g) else None})
        sens = [{"radius_m": r, "n_pressured": int((mine["nearest_opp_m"] < r).sum()),
                 "share": float((mine["nearest_opp_m"] < r).mean()) if len(mine) else None} for r in PRESS_SENSITIVITY_M]
        lo_ci, hi_ci = _wilson(len(ok), n_pr)
        return {
            "mean_pressure": float(mine["pressure"].mean()) if len(mine) else None,
            "pressure_levels": levels, "radius_sensitivity": sens,
            "success_rate_under_pressure_ci": [lo_ci, hi_ci] if n_pr else None,
            "reliable": bool(n_pr >= 15),
            "note_pressure": "Pressure 0-1: how close the opponents are when he acts (5 m or more = 0, on top of him = 1). "
                             "'Pressured' = an opponent within 3 m. With fewer than 15 pressured actions the percentages are only a rough guide.",
            "radius_m": PRESS_RADIUS_M, "threshold": PRESS_RADIUS_M, "n_actions": int(len(mine)),
            "mean_nearest_opp_m": float(mine["nearest_opp_m"].mean()) if len(mine) else None, "n_pressured": int(n_pr),
            "pressured_share": float(n_pr / len(mine)) if len(mine) else None,
            "success_rate_under_pressure": float(len(ok) / n_pr) if n_pr else None,
            "success_rate_free": float(mine[~mine["pressured"]]["success"].mean()) if (~mine["pressured"]).any() else None,
            "value_generated": value,
            "rating": float(100.0 * value / n_pr) if n_pr else None,  # VAEP gained per 100 pressured actions
        }

    # =====================================================================
    # 2. Fatigue decay (15-minute blocks)
    # =====================================================================
    def _compute_fatigue(self) -> pd.DataFrame:
        """Pitch-control area of every player, sampled every FATIGUE_SAMPLE_S seconds."""
        m, e = self.m, self.e
        step = max(1, int(round(FATIGUE_SAMPLE_S * m.fps)))
        rows = []
        for idx in range(0, m.n_frames, step):
            if e.possession_side(idx) is None or not np.isfinite(m.ball_x[idx]):
                continue  # only live play: the ball must be tracked, so every sample compares like with like
            for slot, area in e.player_control_area(idx).items():
                rows.append((idx, int(m.bin_id[idx]), slot, area))
        return pd.DataFrame(rows, columns=["idx", "bin_id", "slot", "area_m2"])

    def fatigue_report(self, slot: int) -> dict:
        m = self.m
        samples = self._get("fatigue")
        av = self.e.action_values()
        dec = self._get("decisions")
        mine = samples[samples["slot"] == slot]
        present = ~np.isnan(m.X[:, slot])
        rows = []
        for b in range(len(BIN_LABELS)):
            fmask = (m.bin_id == b) & present
            minutes_on = float(fmask.sum()) / m.fps / 60.0
            if minutes_on <= 0:
                continue
            # the pitch-control samples only come from live play (ball tracked), so distance, speed and the "enough minutes"
            # test use the same live frames; otherwise dead-ball minutes would dilute some blocks and not others
            lmask = fmask & np.isfinite(m.ball_x)
            live_minutes = float(lmask.sum()) / m.fps / 60.0
            s = mine[mine["bin_id"] == b]
            a = av[(av["slot"] == slot) & (av["bin_id"] == b)] if len(av) else av
            d = dec[(dec["slot"] == slot) & (dec["bin_id"] == b)] if len(dec) else dec
            speed = m.SPEED[lmask, slot]
            speed = np.where(speed <= 10.0, speed, np.nan)  # > 36 km/h is a tracking jump, not running
            rows.append({
                "bin": b, "label": BIN_LABELS[b], "minutes_on_pitch": minutes_on, "live_minutes": live_minutes,
                "area_m2": float(s["area_m2"].mean()) if len(s) else None,
                "radius_m": float(np.sqrt(s["area_m2"] / np.pi).mean()) if len(s) else None,
                "n_samples": int(len(s)),
                "vaep_per_action": float(a["vaep_oa"].mean()) if len(a) else None, "n_actions": int(len(a)),
                "decision_score": float(d["decision_score"].mean()) if len(d) else None, "n_passes": int(len(d)),
                "distance_m": float(np.nansum(speed) / m.fps),
                "distance_per_live_min": float(np.nansum(speed) / m.fps / live_minutes) if live_minutes > 0.5 else None, "mean_speed": float(np.nanmean(speed)) if np.isfinite(speed).any() else None,
            })
        # change vs. the player's first meaningful block
        base = next((r for r in rows if r["radius_m"] and r["live_minutes"] >= MIN_MINUTES_FOR_TREND), None)
        for r in rows:
            r["radius_change_pct"] = (100.0 * (r["radius_m"] / base["radius_m"] - 1.0)
                                      if base and r["radius_m"] and r["live_minutes"] >= MIN_MINUTES_FOR_TREND else None)
            r["vaep_change"] = (r["vaep_per_action"] - base["vaep_per_action"]
                                if base and base["vaep_per_action"] is not None and r["vaep_per_action"] is not None else None)
        return {"bins": rows, "baseline_bin": base["label"] if base else None,
                "note": "Radius = sqrt(A/pi) with A = pitch-control area the player controls on his own. "
                        f"Blocks with < {MIN_MINUTES_FOR_TREND:.0f} min of live play (ball in play) are not compared. "
                        "Distance and speed also count live play only, so blocks are comparable."}

    # =====================================================================
    # 3. Chemistry matrix
    # =====================================================================
    def chemistry(self, side: str) -> dict:
        av = self.e.action_values()
        if not len(av):
            return {"players": [], "matrix": [], "counts": [], "top_duos": []}
        ps = av[(av["action"] == "pass") & av["success"] & (av["receiver_slot"] >= 0) & (av["slot"] >= 0)].copy()
        if not len(ps):
            return {"players": [], "matrix": [], "counts": [], "top_duos": []}
        # zone baseline: 6 x 4 zones in the attacker's frame
        adir = np.array([self.m.attack_direction(s, int(i)) for s, i in zip(ps["side"], ps["frame_idx"])])
        zx = np.clip(np.floor((ps["x"].to_numpy() * adir + 52.5) / (105.0 / 6)).astype(int), 0, 5)
        zy = np.clip(np.floor((ps["y"].to_numpy() * adir + 34.0) / (68.0 / 4)).astype(int), 0, 3)
        ps["zone"] = zx * 4 + zy
        zone_mean = ps.groupby("zone")["delta_epv"].agg(["mean", "count"])
        global_mean = float(ps["delta_epv"].mean())
        w = zone_mean["count"] / (zone_mean["count"] + 5.0)  # shrink thin zones towards the global mean
        baseline = (w * zone_mean["mean"] + (1 - w) * global_mean).to_dict()
        ps["expected"] = ps["zone"].map(baseline)
        ps["uplift"] = ps["delta_epv"] - ps["expected"]
        ps = ps[ps["side"] == side]
        pair = ps.groupby(["slot", "receiver_slot"]).agg(n=("uplift", "size"), uplift=("uplift", "mean"),
                                                         total=("uplift", "sum")).reset_index()
        pair = pair[pair["n"] >= MIN_PASSES_PAIR]
        if not len(pair):
            return {"players": [], "matrix": [], "counts": [], "top_duos": [], "min_passes": MIN_PASSES_PAIR}
        slots = sorted(set(pair["slot"]) | set(pair["receiver_slot"]))
        ix = {s: i for i, s in enumerate(slots)}
        mat = np.full((len(slots), len(slots)), np.nan)
        cnt = np.zeros((len(slots), len(slots)), dtype=int)
        for r in pair.itertuples():
            mat[ix[r.slot], ix[r.receiver_slot]] = r.uplift
            cnt[ix[r.slot], ix[r.receiver_slot]] = r.n
        duos = pair.sort_values("uplift", ascending=False).head(10)
        return {
            "side": side, "min_passes": MIN_PASSES_PAIR,
            "players": [{"slot": int(s), "name": self._name(s), "jersey": self._players.iloc[s]["jersey"],
                         "player_id": self._players.iloc[s]["player_id"]} for s in slots],
            "matrix": mat, "counts": cnt,
            "top_duos": [{"passer": self._name(r.slot), "receiver": self._name(r.receiver_slot), "passer_slot": int(r.slot),
                          "receiver_slot": int(r.receiver_slot), "passes": int(r.n), "uplift": float(r.uplift),
                          "total_uplift": float(r.total)} for r in duos.itertuples()],
            "note": "Uplift = realised dEPV of the pass minus the average completed pass from the same pitch zone.",
        }

    # =====================================================================
    # 4. Decoy Run Index
    # =====================================================================
    def _compute_decoys(self) -> pd.DataFrame:
        m, e = self.m, self.e
        ev = m.events
        T = m.n_frames
        ev_side = ev["side"].map({"home": 0, "away": 1}).fillna(-1).to_numpy().astype(int) if len(ev) else np.array([], dtype=int)
        poss = np.where(m.last_event_idx >= 0, ev_side[np.maximum(m.last_event_idx, 0)] if len(ev_side) else -1, -1)
        ev_fi = ev["frame_idx"].to_numpy() if len(ev) else np.array([], dtype=int)
        ev_slots = np.column_stack([ev["actor_slot"], ev["target_slot"], ev["receiver_slot"]]) if len(ev) else np.zeros((0, 3), int)
        min_frames = int(round(RUN_MIN_S * m.fps))
        look = int(round(DECOY_LOOKAHEAD_S * m.fps))
        rows = []
        for slot in range(m.n_players):
            side = self._side_arr[slot]
            code = 0 if side == "home" else 1
            sp = m.SPEED[:, slot]
            fast = np.nan_to_num(sp, nan=0.0) >= RUN_SPEED
            edges = np.diff(np.concatenate(([0], fast.astype(np.int8), [0])))
            for s, t in zip(np.flatnonzero(edges == 1), np.flatnonzero(edges == -1)):
                if t - s < min_frames or m.period[s] != m.period[t - 1]:
                    continue
                if (poss[s:t] == code).mean() < 0.8:
                    continue
                adir = m.attack_direction(side, int(s))
                vx = np.nanmean(m.VX[s:t, slot]) * adir
                if vx < 0.3 * float(np.nanmean(sp[s:t])):  # must be running forward-ish
                    continue
                # decoy = no touch / pass target involving him between start and end + lookahead
                a, b = np.searchsorted(ev_fi, s), np.searchsorted(ev_fi, t + look)
                if len(ev_fi) and (ev_slots[a:b] == slot).any():
                    continue
                d0 = self._das_mates(int(s), slot, side)
                d1 = self._das_mates(int(t - 1), slot, side)
                if d0 is None or d1 is None:
                    continue
                rows.append({"slot": slot, "side": side, "period": int(m.period[s]), "match_minute": float(m.match_minute[s]),
                             "frame_num": int(m.frame_num[s]), "duration_s": (t - s) / m.fps,
                             "mean_speed": float(np.nanmean(sp[s:t])), "das_start": d0, "das_end": d1, "delta_das": d1 - d0})
        return pd.DataFrame(rows)

    def _das_mates(self, idx: int, slot: int, side: str) -> Optional[float]:
        """Dangerous space of the runner's TEAMMATES (the runner himself taken out as a receiver)."""
        e, m = self.e, self.m
        pcr = e.pitch_control(idx)
        if pcr["attacking_side"] != side:
            return None
        where = np.flatnonzero(pcr["slots"] == slot)
        if where.size == 0:  # offside / not present
            return None
        adir = m.attack_direction(side, idx)
        if ref.das_available():
            # reference DAS with the runner taken out as a receiver; the defenders stay where they are (they were dragged)
            r = ref.das_frames(m, [(idx, side, adir, slot)])[0]
            return None if r is None else float(r["das"])
        pcr = e.pitch_control(idx, per_player=True)
        pc_mates = np.clip(pcr["pc_att"] - pcr["ppcf_players"][where[0]], 0.0, 1.0)
        pos = np.column_stack([m.X[idx, pcr["slots"]], m.Y[idx, pcr["slots"]]]).astype(float)
        dl = defensive_line_x(pos[~pcr["is_att"]], adir) if (~pcr["is_att"]).sum() >= 3 else 0.0
        return float(das_surface(pc_mates, m.grid, adir, dl).sum() * m.grid.cell_area)

    def decoy_report(self, slot: int) -> dict:
        d = self._get("decoys")
        if not len(d):
            return {"n_decoy_runs": 0}
        mine = d[d["slot"] == slot]
        top = mine.sort_values("delta_das", ascending=False).head(5)
        return {
            "n_decoy_runs": int(len(mine)),
            "total_delta_das": float(mine["delta_das"].sum()) if len(mine) else 0.0,
            "mean_delta_das": float(mine["delta_das"].mean()) if len(mine) else None,
            "positive_share": float((mine["delta_das"] > 0).mean()) if len(mine) else None,
            "top_runs": top[["period", "match_minute", "frame_num", "duration_s", "mean_speed", "delta_das"]],
            "note": "delta DAS = change in the team's dangerous accessible space (m2, accessible-space package) from the start to the end of the run, with the runner himself taken out as a receiver.",
        }

    # =====================================================================
    # the report used by the API
    # =====================================================================
    def player_report(self, player_id) -> dict:
        row = self.player_row(player_id)
        slot = int(row["slot"])
        rep = {
            "player": {"slot": slot, "player_id": row["player_id"], "name": row["name"], "jersey": row["jersey"],
                       "side": row["side"], "team": row["team_name"], "position": row["position"],
                       "minutes_tracked": round(float(row["frames_present"]) / self.m.fps / 60.0, 1)},
            "decision_efficiency": self.decision_report(slot),
            "fatigue_decay": self.fatigue_report(slot),
            "chemistry": self.chemistry(row["side"]),
            "decoy_run_index": self.decoy_report(slot),
            "press_resistance": self.press_report(slot),
        }
        return _native(rep)


